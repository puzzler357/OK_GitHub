// Загрузка переменных окружения из .env-файлов.
//
// Импортируется первой строкой server.ts: модули вроде src/db/sqlite.ts читают
// process.env на этапе загрузки, поэтому значения должны попасть в окружение
// раньше них. В ESM модули выполняются в порядке объявления импортов.
import dotenv from 'dotenv';

// .env.local — личные значения разработчика, приоритетнее общего .env.
// Уже заданные переменные dotenv не перезаписывает, поэтому окружение CI
// и автотестов всегда выигрывает у файлов.
// quiet убирает подсказки dotenv из вывода сервера и тестов.
dotenv.config({ path: ['.env.local', '.env'], quiet: true });

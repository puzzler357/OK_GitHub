import type { KeyboardEvent } from 'react';

/**
 * Props для элемента, который ведёт себя как кнопка, но кнопкой не является.
 *
 * В разметке много кликабельных карточек, строк таблиц и подложек модалок.
 * Сделать их настоящими <button> нельзя — внутри блочная вёрстка и вложенные
 * интерактивные элементы, — но оставлять их недоступными с клавиатуры тоже
 * нельзя: до половины экранов управлялись только мышью.
 *
 * Помощник добавляет роль, фокусируемость и обработку Enter/Space одним
 * набором, чтобы это не расползалось по двум десяткам мест по-разному.
 */
export function clickable(onClick: () => void, label?: string) {
  return {
    role: 'button' as const,
    tabIndex: 0,
    'aria-label': label,
    onClick,
    onKeyDown: (event: KeyboardEvent) => {
      // Пробел по умолчанию прокручивает страницу — для роли кнопки это не то.
      if (event.key === 'Enter' || event.key === ' ') {
        event.preventDefault();
        onClick();
      }
    },
  };
}
